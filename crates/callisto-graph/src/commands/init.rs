/// Content of the scaffolded `.changeset/README.md`.
pub const CHANGESET_README: &str = "# Changesets

This directory contains markdown changeset files generated by Callisto CLI (`callisto add`).
Each changeset describes a package version bump and associated release summary.
";

const CONFIG_HEADER: &str = "# callisto configuration\n";
const DEFAULT_TAG_CONVENTION: &str = "{name}@{version}";
const SHARED_TAG_CONVENTION: &str = "v{version}";
const TAG_CONVENTIONS: [&str; 4] = [
    DEFAULT_TAG_CONVENTION,
    "{name}-v{version}",
    "{name}-{version}",
    SHARED_TAG_CONVENTION,
];

/// How packages version relative to each other.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Versioning {
    /// Every package shares one version (`[[fixed-group]] name = "all"`).
    Fixed,
    Independent,
}

/// One discovered workspace package.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InitPackage {
    /// Ecosystem-qualified id, e.g. `cargo/app`.
    pub id: String,
    pub version: Version,
    /// Executables the package builds; empty for a library.
    pub bin_names: Vec<String>,
    /// Executables provided by Cargo and eligible for Cargo artifact builds.
    pub cargo_bin_names: Vec<String>,
    /// Ecosystems that provide executables but do not yet have an artifact builder.
    pub unsupported_bin_ecosystems: Vec<String>,
    /// Latest release tag under the package's detected convention.
    pub last_tag: Option<TagName>,
    /// Detected `publish-to` targets (`none` omitted).
    pub publish_to: Vec<String>,
    /// A napi/maturin platform package: never grouped or shipped.
    pub platform: bool,
}

impl InitPackage {
    pub fn is_binary(&self) -> bool {
        !self.platform && !self.bin_names.is_empty()
    }

    fn supports_artifact_builder(&self) -> bool {
        self.id.starts_with("cargo/") && !self.cargo_bin_names.is_empty()
    }

    fn name(&self) -> &str {
        self.id.split_once('/').map_or(self.id.as_str(), |(_, name)| name)
    }
}

/// Everything `init` detects before asking a question.
#[derive(Clone, Debug)]
pub struct InitFacts {
    pub root: PathBuf,
    pub ecosystems: BTreeSet<Ecosystem>,
    pub packages: Vec<InitPackage>,
    /// Canonical `origin` push URL, or `None` when no `origin` remote is configured.
    pub origin: Option<String>,
    /// `origin` as a GitHub `owner/repo`, when it is one.
    pub origin_repository: Option<GitHubRepository>,
    /// Non-default tag templates to write, keyed by qualified package id.
    pub tag_templates: BTreeMap<String, String>,
    /// `false` in a repository with no commit yet, where no release can be planned.
    pub has_commit: bool,
    /// A package ships napi/maturin platform builds -- either its own canonical
    /// manifest is platform-tagged, or a platform package is attached to it from
    /// a sibling directory (`IdentityIndex::platforms_of`, e.g. napi's per-arch
    /// packages). Mirrors `commands::release::local::ci_release_route`'s own
    /// platform-package check.
    pub has_platform_packages: bool,
    /// Some package declares `napi.targets` (`callisto matrix`'s napi entries).
    pub has_napi_targets: bool,
    /// Some package declares `[tool.maturin].targets`.
    pub has_maturin_targets: bool,
}

impl InitFacts {
    pub fn binary_packages(&self) -> impl Iterator<Item = &InitPackage> {
        self.packages
            .iter()
            .filter(|package| package.is_binary() && package.supports_artifact_builder())
    }

    pub fn unsupported_artifact_packages(&self) -> impl Iterator<Item = &InitPackage> {
        self.packages
            .iter()
            .filter(|package| !package.supports_artifact_builder() && !package.unsupported_bin_ecosystems.is_empty())
    }

    /// Resolves `name` (qualified or bare) to a binary-producing package.
    pub fn product_package(&self, name: &str) -> Result<&InitPackage, GraphError> {
        let invalid = |reason| GraphError::InitInvalidProductPackage {
            package: name.to_owned(),
            reason,
            candidates: self.binary_packages().map(|package| package.id.clone()).collect(),
        };
        let found: Vec<&InitPackage> = match self.packages.iter().find(|package| package.id == name) {
            Some(package) => vec![package],
            None => self.packages.iter().filter(|package| package.name() == name).collect(),
        };
        match found.as_slice() {
            [package] if package.is_binary() && package.supports_artifact_builder() => Ok(package),
            [package] if package.is_binary() => Err(GraphError::InitUnsupportedArtifactBuilder {
                package: package.id.clone(),
                ecosystem: package.unsupported_bin_ecosystems.first().cloned().unwrap_or_else(|| {
                    package
                        .id
                        .split_once('/')
                        .map_or("unknown", |(ecosystem, _)| ecosystem)
                        .to_owned()
                }),
            }),
            [_] => Err(invalid("it does not produce a binary artifact")),
            _ => Err(invalid("it is not a workspace package")),
        }
    }
}

/// Opt-in to shipping binaries as GitHub release assets.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BinaryRelease {
    /// Qualified id of the product package.
    pub product: String,
    pub forge_repository: GitHubRepository,
    pub targets: Vec<String>,
}

/// The operator's intent; everything else is detected.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InitAnswers {
    pub versioning: Versioning,
    pub binaries: Option<BinaryRelease>,
}

fn io_err(path: &Path) -> impl Fn(std::io::Error) -> GraphError + '_ {
    move |error| GraphError::InitIo {
        path: path.to_path_buf(),
        message: error.to_string(),
    }
}

fn ensure_uninitialized(root: &Path) -> Result<(), GraphError> {
    let path = root.join("callisto.toml");
    if callisto_model::strict_fs::exists(&path).map_err(io_err(&path))? {
        return Err(GraphError::InitAlreadyInitialized { path });
    }
    Ok(())
}

fn qualified_id(package: &callisto_model::Package) -> String {
    match package.canonical_manifests().next() {
        Some(manifest) => format!("{}/{}", manifest.ecosystem().prefix(), package.id.name()),
        None => package.id.display_name(),
    }
}

/// Detects the workspace facts `init` reports and builds on.
///
/// # Errors
///
/// An existing `callisto.toml`, no Git repository, no usable `origin`, or an
/// ambiguous tag convention.
pub fn detect<L: ProjectLocator, R: CommandRunner>(
    root: &Path,
    locator: &L,
    runner: &R,
) -> Result<InitFacts, GraphError> {
    let root = canonical_root(root)?;
    ensure_uninitialized(&root)?;
    let git_dir = runner.run_with_timeout(programs::GIT, &["rev-parse", "--git-dir"], &root, timeouts::LOCAL_GIT)?;
    if git_dir.exit_code != Some(0) {
        return Err(GraphError::InitNotGitRepository { root });
    }
    let origin = optional_git_remote(&root, runner)?;
    let head = runner.run_with_timeout(
        programs::GIT,
        &["rev-parse", "--verify", "--quiet", "HEAD"],
        &root,
        timeouts::LOCAL_GIT,
    )?;

    let discovered = Workspace::load(root.clone(), locator, runner)?;
    let tag_templates = detect_tag_templates(&discovered)?;
    let templates_only = InitFacts {
        root: root.clone(),
        ecosystems: BTreeSet::new(),
        packages: Vec::new(),
        origin: origin.as_ref().map(|remote| remote.endpoint.clone()),
        origin_repository: origin.as_ref().and_then(|remote| remote.github_repository.clone()),
        tag_templates,
        has_commit: head.exit_code == Some(0),
        has_platform_packages: false,
        has_napi_targets: false,
        has_maturin_targets: false,
    };
    let config = resolve_config_text(
        &root,
        &render_config(
            &templates_only,
            &InitAnswers {
                versioning: Versioning::Independent,
                binaries: None,
            },
        ),
    )?;
    let workspace = Workspace::load_with_config(root.clone(), config, locator, runner)?;
    let tags = workspace.tags()?;
    let versions = workspace.base_versions()?;
    let ctx = callisto_manifests::OpenContext::for_workspace_root(&workspace.root)?;

    let mut packages = Vec::new();
    for package in workspace.graph.packages() {
        let mut bin_names = Vec::new();
        let mut cargo_bin_names = Vec::new();
        let mut unsupported_bin_ecosystems = BTreeSet::new();
        for decl in package.canonical_manifests() {
            let manifest = crate::manifest_cache::open_cached(&workspace.manifest_cache, decl, &ctx)?;
            let names = manifest.bin_names()?;
            if manifest.ecosystem() == Ecosystem::Cargo {
                cargo_bin_names.extend(names.iter().cloned());
            } else if !names.is_empty() {
                unsupported_bin_ecosystems.insert(manifest.ecosystem().prefix().to_owned());
            }
            bin_names.extend(names);
        }
        packages.push(InitPackage {
            id: qualified_id(package),
            version: versions[&package.id].clone(),
            bin_names,
            cargo_bin_names,
            unsupported_bin_ecosystems: unsupported_bin_ecosystems.into_iter().collect(),
            last_tag: tags.last_tag(&package.id).map(|tag| tag.name.clone()),
            publish_to: package
                .publish_to
                .iter()
                .map(|target| target.config_str().to_owned())
                .filter(|target| target != PublishTarget::None.config_str())
                .collect(),
            platform: is_platform_package(package),
        });
    }
    packages.sort_by(|a, b| a.id.cmp(&b.id));
    let ecosystems = workspace
        .graph
        .packages()
        .flat_map(|package| package.canonical_manifests())
        .map(|manifest| manifest.ecosystem())
        .collect();
    // Counts attached platform packages too: they never get their own `packages` entry,
    // so scanning canonical manifests alone finds only co-located ones.
    let has_platform_packages = workspace
        .graph
        .packages()
        .any(|package| is_platform_package(package) || workspace.identity.platforms_of(&package.id).next().is_some());

    let matrix = crate::commands::matrix::matrix(&workspace, &crate::commands::matrix::MatrixOptions::default())?;
    let has_kind = |kind| matrix.platform_targets.values().any(|group| group.kind == kind);

    Ok(InitFacts {
        ecosystems,
        packages,
        has_platform_packages,
        has_napi_targets: has_kind(callisto_model::PlatformTargetKind::Napi),
        has_maturin_targets: has_kind(callisto_model::PlatformTargetKind::Maturin),
        ..templates_only
    })
}

/// One tag convention a package's existing tags follow.
struct TagMatch {
    convention: &'static str,
    template: String,
    tags: Vec<String>,
}

/// Matches each package's tags against the candidate conventions; returns the non-default ones to write.
fn detect_tag_templates<R: CommandRunner, D: DependencyResolver>(
    workspace: &Workspace<'_, R, D>,
) -> Result<BTreeMap<String, String>, GraphError> {
    let all_tags = crate::tags::fetch_all_tags(workspace.git_access())?;
    let mut matches: BTreeMap<String, Vec<TagMatch>> = BTreeMap::new();
    for package in workspace
        .graph
        .packages()
        .filter(|package| !is_platform_package(package))
    {
        let grammar = package.version_grammar()?;
        for convention in TAG_CONVENTIONS {
            let rendered = if convention == DEFAULT_TAG_CONVENTION {
                TagTemplate::default_for(&package.id).as_str()
            } else {
                convention.replace("{name}", package.id.name())
            };
            let Ok(template) = TagTemplate::parse(&rendered) else {
                continue;
            };
            // A leading digit keeps `{name}-{version}` from claiming `{name}-v1.0.0` under PEP 440.
            let tags: Vec<String> = all_tags
                .iter()
                .filter(|tag| {
                    template.extract_version_str(tag).is_some_and(|version| {
                        version.starts_with(|c: char| c.is_ascii_digit()) && Version::parse(version, grammar).is_ok()
                    })
                })
                .cloned()
                .collect();
            if !tags.is_empty() {
                matches.entry(qualified_id(package)).or_default().push(TagMatch {
                    convention,
                    template: rendered,
                    tags,
                });
            }
        }
    }

    let shared: Vec<String> = matches
        .iter()
        .filter(|(_, found)| found.iter().any(|found| found.convention == SHARED_TAG_CONVENTION))
        .map(|(package, _)| package.clone())
        .collect();
    if shared.len() > 1 {
        return Err(GraphError::InitSharedVersionTag { packages: shared });
    }

    let mut templates = BTreeMap::new();
    for (package, found) in matches {
        match found.as_slice() {
            [only] => {
                if only.convention != DEFAULT_TAG_CONVENTION {
                    templates.insert(package, only.template.clone());
                }
            }
            _ => {
                return Err(GraphError::InitTagTemplateAmbiguous {
                    package,
                    matches: found
                        .iter()
                        .map(|found| format!("`{}` ({})", found.template, found.tags.join(", ")))
                        .collect(),
                })
            }
        }
    }
    Ok(templates)
}

/// Renders `callisto.toml` from the answers: only answered intent and tag continuity, never defaults.
pub fn render_config(facts: &InitFacts, answers: &InitAnswers) -> String {
    use toml_edit::{value, Array, ArrayOfTables, DocumentMut, Item, Table};

    let mut doc = DocumentMut::new();
    if answers.versioning == Versioning::Fixed {
        let members: Array = facts
            .packages
            .iter()
            .filter(|package| !package.platform)
            .map(|package| package.id.as_str())
            .collect();
        if !members.is_empty() {
            let mut group = Table::new();
            group["name"] = value("all");
            group["members"] = value(members);
            let mut groups = ArrayOfTables::new();
            groups.push(group);
            doc["fixed-group"] = Item::ArrayOfTables(groups);
        }
    }
    let mut rules: BTreeMap<&str, Table> = BTreeMap::new();
    for (package, template) in &facts.tag_templates {
        rules.entry(package).or_default()["tag-template"] = value(template.as_str());
    }
    let product = answers
        .binaries
        .as_ref()
        .and_then(|release| facts.packages.iter().find(|package| package.id == release.product));
    if let Some(product) = product {
        // Artifact slots derive only for a product that publishes to github-release.
        let publish_to: Array = product
            .publish_to
            .iter()
            .map(String::as_str)
            .chain([PublishTarget::GitHubRelease.config_str()])
            .collect();
        rules.entry(&product.id).or_default()["publish-to"] = value(publish_to);
    }
    if !rules.is_empty() {
        let mut tables = ArrayOfTables::new();
        for (package, rule) in rules {
            let mut table = Table::new();
            table["match"] = value(package);
            table.extend(rule);
            tables.push(table);
        }
        doc["package"] = Item::ArrayOfTables(tables);
    }
    if let Some(release) = &answers.binaries {
        let bin_names = product
            .map(|package| package.cargo_bin_names.as_slice())
            .unwrap_or_default();
        let mut table = Table::new();
        table["product-package"] = value(release.product.as_str());
        table["forge-repository"] = value(release.forge_repository.as_slug());
        let mut artifacts = ArrayOfTables::new();
        for target in &release.targets {
            for bin in bin_names {
                let extension = if target.contains("windows") { "zip" } else { "tar.gz" };
                let mut artifact = Table::new();
                artifact["package"] = value(release.product.as_str());
                artifact["target"] = value(target.as_str());
                artifact["asset-name"] = value(format!("{bin}-{target}.{extension}"));
                artifacts.push(artifact);
            }
        }
        table["artifact"] = Item::ArrayOfTables(artifacts);
        doc["release"] = Item::Table(table);
    }
    let body = doc.to_string();
    if body.is_empty() {
        CONFIG_HEADER.to_owned()
    } else {
        format!("{CONFIG_HEADER}\n{body}")
    }
}

fn resolve_config_text(root: &Path, text: &str) -> Result<ResolvedConfig, GraphError> {
    let raw = toml::from_str::<RawConfig>(text).map_err(|error| ConfigError::ParseToml {
        path: root.join("callisto.toml"),
        message: error.to_string(),
    })?;
    Ok(crate::config::resolve(root, raw)?)
}

/// The first release `config` would produce, from the plan behind `release --dry-run`.
///
/// # Errors
///
/// `config` fails to resolve, or the release plan cannot be derived.
pub fn preview<L: ProjectLocator, R: CommandRunner>(
    facts: &InitFacts,
    config: &str,
    locator: &L,
    runner: &R,
) -> Result<Option<LocalReleasePlan>, GraphError> {
    let resolved = resolve_config_text(&facts.root, config)?;
    let workspace = Workspace::load_with_config(facts.root.clone(), resolved, locator, runner)?;
    plan_workspace_release(&workspace, &[], LocalReleaseSource::Preview)
}

/// Parses a forge repository answer, which the release plan requires to be `origin`'s GitHub repository.
///
/// # Errors
///
/// `value` is not a GitHub `owner/repo`, or is not `origin`'s.
pub fn forge_repository(facts: &InitFacts, value: &str) -> Result<GitHubRepository, GraphError> {
    let repository = GitHubRepository::parse(value.trim()).map_err(|error| GraphError::InitInvalidForgeRepository {
        value: value.to_owned(),
        reason: error.to_string(),
    })?;
    if facts.origin_repository.as_ref() != Some(&repository) {
        return Err(GraphError::InitForgeRepositoryMismatch {
            configured: repository.as_slug(),
            origin: facts.origin.clone().unwrap_or_else(|| "none".to_owned()),
        });
    }
    Ok(repository)
}

/// Validates artifact target triples.
///
/// # Errors
///
/// An empty or repeated triple.
pub fn validate_targets(targets: &[String]) -> Result<Vec<String>, GraphError> {
    let mut seen = BTreeSet::new();
    for target in targets {
        let invalid = |reason| GraphError::InitInvalidTargetTriple {
            triple: target.clone(),
            reason,
        };
        if target.trim().is_empty() {
            return Err(invalid("it is empty"));
        }
        if !seen.insert(target.as_str()) {
            return Err(invalid("it is given more than once"));
        }
    }
    Ok(targets.to_vec())
}

/// Files `init` writes, or would write under `--dry-run`: `callisto.toml`, `.changeset/README.md`
/// unless it already exists, and the release workflow when `workflow` is `true`. Reads current
/// disk state, so callers compute this before writing anything.
///
/// # Errors
///
/// The README's existence cannot be determined.
pub fn init_files(root: &Path, workflow: bool) -> Result<Vec<PathBuf>, GraphError> {
    let readme = root.join(".changeset/README.md");
    let mut files = vec![root.join("callisto.toml")];
    if !callisto_model::strict_fs::exists(&readme).map_err(io_err(&readme))? {
        files.push(readme);
    }
    if workflow {
        files.push(workflow_path(root));
    }
    Ok(files)
}

/// Writes `callisto.toml` and, when absent, `.changeset/README.md`.
///
/// # Errors
///
/// `callisto.toml` already exists, or a write fails.
pub fn write(root: &Path, config: &str, permit: &ApplyPermit) -> Result<InitReport, GraphError> {
    ensure_uninitialized(root)?;
    let config_path = root.join("callisto.toml");
    let files = init_files(root, false)?;
    callisto_model::atomic::atomic_write(&config_path, config, permit).map_err(io_err(&config_path))?;
    write_changeset_readme(root, permit)?;
    Ok(InitReport {
        schema_version: SCHEMA_VERSION,
        initialized: true,
        config_path,
        config: config.to_owned(),
        files,
        diagnostics: Vec::new(),
    })
}

/// Creates `.changeset/README.md` unless it already exists.
///
/// # Errors
///
/// A directory or file write fails.
pub fn write_changeset_readme(root: &Path, permit: &ApplyPermit) -> Result<(), GraphError> {
    let readme = root.join(".changeset/README.md");
    if callisto_model::strict_fs::exists(&readme).map_err(io_err(&readme))? {
        return Ok(());
    }
    let changeset_dir = root.join(".changeset");
    std::fs::create_dir_all(&changeset_dir).map_err(io_err(&changeset_dir))?;
    callisto_model::atomic::atomic_write(&readme, CHANGESET_README, permit).map_err(io_err(&readme))
}

/// `@changesets/cli` `config.json` keys callisto never reads, and the callisto.toml construct
/// that replaces each one, when one exists.
const CHANGESETS_CONFIG_KEYS: [(&str, Option<&str>); 6] = [
    ("fixed", Some("[[fixed-group]]")),
    ("linked", None),
    ("ignore", None),
    ("access", None),
    ("baseBranch", None),
    ("updateInternalDependencies", None),
];

/// Warns, per key, about every `.changeset/config.json` key callisto ignores.
///
/// callisto never translates this file; a present, unhonoured key is silently inert otherwise.
/// Returns no diagnostics when the file is absent or is not a JSON object.
pub fn changesets_config_diagnostics(root: &Path) -> Vec<Diagnostic> {
    let path = root.join(".changeset/config.json");
    let Ok(text) = std::fs::read_to_string(&path) else {
        return Vec::new();
    };
    let Ok(serde_json::Value::Object(config)) = serde_json::from_str(&text) else {
        return Vec::new();
    };
    CHANGESETS_CONFIG_KEYS
        .iter()
        .filter(|(key, _)| config.contains_key(*key))
        .map(|(key, equivalent)| {
            let message = match equivalent {
                Some(equivalent) => {
                    format!("`.changeset/config.json` key `{key}` is not honoured; use {equivalent} instead")
                }
                None => format!("`.changeset/config.json` key `{key}` is not honoured; callisto has no equivalent"),
            };
            Diagnostic {
                code: DiagnosticCode::ChangesetsConfigKeyDropped,
                severity: DiagnosticSeverity::Warning,
                message,
                package: None,
                path: Some(path.clone()),
                escalated_by: None,
                governed_by: None,
            }
        })
        .collect()
}

/// The config `write` would produce for `root` with no answers: a header only.
pub fn empty_config() -> &'static str {
    CONFIG_HEADER
}

/// Path `init` writes a generated GitHub Actions release workflow to: the one
/// workflow `release plan` binds artifact attestations to.
pub fn workflow_path(root: &Path) -> PathBuf {
    root.join(callisto_model::RELEASE_COORDINATOR_WORKFLOW_PATH)
}

/// Which release workflow `init` generates.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WorkflowShape {
    /// Two jobs: `version-pr` and `callisto release`.
    Simple,
    /// `version-pr` plus plan -> build (matrix) -> execute,
    /// for `[[release.artifact]]` slots or napi platform packages.
    BuildMatrix,
}

/// Why `init` generates no workflow for a workspace.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WorkflowUnsupported {
    /// maturin platform builds have no generated build job.
    Maturin,
    /// Platform packages exist, but no package declares `napi.targets` to build them from.
    PlatformPackagesWithoutNapiTargets,
}

impl std::fmt::Display for WorkflowUnsupported {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Maturin => {
                formatter.write_str("maturin platform builds (`[tool.maturin].targets`) are not generated")
            }
            Self::PlatformPackagesWithoutNapiTargets => {
                formatter.write_str("the workspace has platform packages but no package declares `napi.targets`")
            }
        }
    }
}

/// The workflow shape `init` generates for this workspace and answers.
///
/// # Errors
///
/// The workspace has a shape no generated workflow covers.
pub fn workflow_shape(facts: &InitFacts, answers: &InitAnswers) -> Result<WorkflowShape, WorkflowUnsupported> {
    if facts.has_maturin_targets {
        Err(WorkflowUnsupported::Maturin)
    } else if facts.has_platform_packages && !facts.has_napi_targets {
        Err(WorkflowUnsupported::PlatformPackagesWithoutNapiTargets)
    } else if answers.binaries.is_some() || facts.has_platform_packages {
        Ok(WorkflowShape::BuildMatrix)
    } else {
        Ok(WorkflowShape::Simple)
    }
}

/// Where [`default_branch`]'s branch name came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DefaultBranchSource {
    /// The local `refs/remotes/origin/HEAD` ref, set by `git clone` or `git remote set-head`.
    OriginHead,
    /// `git ls-remote --symref origin HEAD`, queried when the local ref above is unset.
    RemoteHead,
    /// The branch currently checked out: no remote reports a HEAD (e.g. `origin` is unset).
    CurrentBranch,
    /// No remote and no checked-out branch (e.g. a fresh repo with no commits): `main`.
    Fallback,
}

impl std::fmt::Display for DefaultBranchSource {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::OriginHead => "origin/HEAD",
            Self::RemoteHead => "origin, queried live",
            Self::CurrentBranch => "the current branch",
            Self::Fallback => "fallback: none of the above resolved",
        })
    }
}

/// The repository's default branch and where that name came from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DefaultBranch {
    pub name: String,
    pub source: DefaultBranchSource,
}

/// The repository's default branch: local `origin/HEAD`, else a live query of `origin`,
/// else the branch currently checked out, else `main`.
pub fn default_branch<R: CommandRunner>(runner: &R, root: &Path) -> DefaultBranch {
    if let Some(name) = local_origin_head(runner, root) {
        return DefaultBranch {
            name,
            source: DefaultBranchSource::OriginHead,
        };
    }
    if let Some(name) = remote_origin_head(runner, root) {
        return DefaultBranch {
            name,
            source: DefaultBranchSource::RemoteHead,
        };
    }
    if let Some(name) = current_branch(runner, root) {
        return DefaultBranch {
            name,
            source: DefaultBranchSource::CurrentBranch,
        };
    }
    DefaultBranch {
        name: "main".to_owned(),
        source: DefaultBranchSource::Fallback,
    }
}

/// The last path segment of a `refs/...` line, e.g. `refs/heads/trunk` -> `trunk`.
fn last_ref_segment(reference: &str) -> Option<String> {
    let branch = reference.trim().rsplit('/').next()?;
    (!branch.is_empty()).then(|| branch.to_owned())
}

// A repository with no `origin/HEAD` (a fresh clone, or one built by hand, as in tests)
// fails this on the common path, not just exceptionally.
fn local_origin_head<R: CommandRunner>(runner: &R, root: &Path) -> Option<String> {
    let output = runner
        .run_quiet(
            programs::GIT,
            &["symbolic-ref", "refs/remotes/origin/HEAD"],
            root,
            timeouts::LOCAL_GIT,
        )
        .ok()?;
    if output.exit_code != Some(0) {
        return None;
    }
    last_ref_segment(&output.stdout)
}

// A shallow or hand-built clone (or one `remote set-head` never ran on) has no local
// `origin/HEAD`; asking the remote directly still resolves it without a fetch.
fn remote_origin_head<R: CommandRunner>(runner: &R, root: &Path) -> Option<String> {
    let output = runner
        .run_quiet(
            programs::GIT,
            &["ls-remote", "--symref", "origin", "HEAD"],
            root,
            timeouts::GIT_LS_REMOTE,
        )
        .ok()?;
    if output.exit_code != Some(0) {
        return None;
    }
    // Output line shape: "ref: refs/heads/<branch>\tHEAD".
    output.stdout.lines().find_map(|line| {
        let (target, name) = line.strip_prefix("ref: ")?.split_once('\t')?;
        (name.trim() == "HEAD").then(|| last_ref_segment(target))?
    })
}

// No remote at all (e.g. `init` in a repo built by hand with no `origin`): the branch
// actually checked out is a better guess than a hardcoded `main`.
fn current_branch<R: CommandRunner>(runner: &R, root: &Path) -> Option<String> {
    let output = runner
        .run_quiet(
            programs::GIT,
            &["symbolic-ref", "--short", "HEAD"],
            root,
            timeouts::LOCAL_GIT,
        )
        .ok()?;
    if output.exit_code != Some(0) {
        return None;
    }
    let branch = output.stdout.trim();
    (!branch.is_empty()).then(|| branch.to_owned())
}

// Rendered with `replace`, not `format!`, so `${{ ... }}` needs no escaping; `.tmpl` so it never reads as a workflow.
const WORKFLOW_TEMPLATE: &str = include_str!("../templates/simple_workflow.tmpl");

const MATRIX_WORKFLOW_TEMPLATE: &str = include_str!("../templates/matrix_workflow.tmpl");

const BUILD_REQUIREMENT: &str = "build==1.4.4";
const TWINE_REQUIREMENT: &str = "twine==7.0.0";

/// Installs the Python build and upload tools into a venv put on the PATH of the later steps; carries no secrets.
const SIMPLE_PYTHON_TOOLS_STEP: &str = "      - name: Install the Python publishing tools
        run: |
          set -euo pipefail
          python3 -m venv \"$RUNNER_TEMP/publish-venv\"
          \"$RUNNER_TEMP/publish-venv/bin/python\" -m pip install --quiet __BUILD__ __TWINE__
          echo \"$RUNNER_TEMP/publish-venv/bin\" >> \"$GITHUB_PATH\"
";

/// Resolves `callisto@<version>`'s commit SHA on `orin-dx/callisto`'s remote.
///
/// GitHub's runner splits a `uses:` reference at the LAST `@` in the whole
/// string (`ActionManifestManagerWrapper.ParseActionReference` in
/// `actions/runner`), so a ref that itself contains `@` -- like the
/// `callisto@<version>` tag this project releases under -- can never be
/// written directly as `owner/repo/path@callisto@<version>`: the split lands
/// inside the ref, not before it, and resolution fails. The generated
/// workflow pins to this tag's resolved commit instead, like every other
/// external action reference in this repository.
///
/// # Errors
///
/// The remote is unreachable, or `callisto@<version>` is not a published tag.
pub fn resolve_release_commit<R: CommandRunner>(runner: &R, root: &Path, version: &str) -> Result<String, GraphError> {
    const ENDPOINT: &str = "https://github.com/orin-dx/callisto.git";
    let reference = format!("refs/tags/callisto@{version}");
    // The peeled ref resolves an annotated tag to its commit; a lightweight
    // tag has no peeled line, and its own SHA already is the commit.
    let peeled = format!("{reference}^{{}}");
    // A transport-level failure (git not found, timed out, ...) keeps its
    // real cause via `GraphError::Command`; only a clean run that still
    // can't find the tag becomes `InitWorkflowVersionUnresolved`.
    let output = runner.run_quiet(
        programs::GIT,
        &["ls-remote", ENDPOINT, &reference, &peeled],
        root,
        timeouts::GIT_LS_REMOTE,
    )?;
    let unresolved = || GraphError::InitWorkflowVersionUnresolved {
        version: version.to_owned(),
    };
    if output.exit_code != Some(0) {
        return Err(unresolved());
    }
    let mut tag_object = None;
    let mut commit = None;
    for line in output.stdout.lines() {
        let Some((sha, found)) = line.split_once('\t') else {
            continue;
        };
        match found.trim() {
            found if found == peeled => commit = Some(sha.trim().to_owned()),
            found if found == reference => tag_object = Some(sha.trim().to_owned()),
            _ => {}
        }
    }
    commit.or(tag_object).ok_or_else(unresolved)
}

/// The repository secrets the generated workflow reads, one per registry ecosystem the workspace has.
pub fn registry_secret_names(facts: &InitFacts) -> Vec<&'static str> {
    [
        (Ecosystem::Cargo, "CARGO_REGISTRY_TOKEN"),
        (Ecosystem::Npm, "NPM_TOKEN"),
        (Ecosystem::Pypi, "PYPI_TOKEN"),
    ]
    .into_iter()
    .filter(|(ecosystem, _)| facts.ecosystems.contains(ecosystem))
    .map(|(_, name)| name)
    .collect()
}

/// Renders the release workflow for `shape`.
///
/// `commit` pins the generated `orin-dx/callisto` action references to the
/// resolved commit of `callisto@<version>` (see [`resolve_release_commit`]);
/// `version` names the CLI `setup-callisto` installs and a trailing comment.
pub fn render_workflow(facts: &InitFacts, shape: WorkflowShape, branch: &str, commit: &str, version: &str) -> String {
    let mut secrets = Vec::new();
    for name in registry_secret_names(facts) {
        secrets.push(format!("{name}: ${{{{ secrets.{name} }}}}"));
        if name == "NPM_TOKEN" {
            // Uses the job's id-token: write; npm publishes no provenance without it.
            secrets.push("NPM_CONFIG_PROVENANCE: \"true\"".to_owned());
        }
    }
    secrets.push("GH_TOKEN: ${{ github.token }}".to_owned());
    let env_lines: Vec<String> = secrets.iter().map(|line| format!("          {line}")).collect();
    let release_env = format!("env:\n{}", env_lines.join("\n"));

    let template = match shape {
        WorkflowShape::Simple => WORKFLOW_TEMPLATE,
        WorkflowShape::BuildMatrix => MATRIX_WORKFLOW_TEMPLATE,
    };
    let python_tools = if facts.ecosystems.contains(&Ecosystem::Pypi) {
        SIMPLE_PYTHON_TOOLS_STEP
    } else {
        ""
    };
    template
        .replace("      __PYTHON_TOOLS__\n", python_tools)
        .replace("__BUILD__", BUILD_REQUIREMENT)
        .replace("__TWINE__", TWINE_REQUIREMENT)
        .replace("__BRANCH__", branch)
        .replace("__COMMIT__", commit)
        .replace("__VERSION__", version)
        .replace("        __RELEASE_ENV__", &format!("        {release_env}"))
}

/// Errors if a workflow file already exists at [`workflow_path`], without writing.
///
/// # Errors
///
/// A file already exists at that path.
pub fn ensure_workflow_absent(root: &Path) -> Result<(), GraphError> {
    let path = workflow_path(root);
    if callisto_model::strict_fs::exists(&path).map_err(io_err(&path))? {
        return Err(GraphError::InitWorkflowExists { path });
    }
    Ok(())
}

/// Writes the generated release workflow.
///
/// # Errors
///
/// A workflow file already exists at [`workflow_path`], or the write fails.
pub fn write_workflow(root: &Path, content: &str, permit: &ApplyPermit) -> Result<(), GraphError> {
    ensure_workflow_absent(root)?;
    let path = workflow_path(root);
    callisto_model::atomic::atomic_write(&path, content, permit).map_err(io_err(&path))
}

